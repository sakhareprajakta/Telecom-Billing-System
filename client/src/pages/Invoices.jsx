import React, { useState, useEffect } from 'react';
import useAuth from '../hooks/useAuth';
import { invoiceApi } from '../services/invoiceApi';
import DataTable from '../components/common/DataTable';
import Button from '../components/common/Button';
import Modal from '../components/common/Modal';
import InvoiceDetails from '../components/billing/InvoiceDetails';
import InvoiceFilter from '../components/billing/InvoiceFilter';
import InvoiceTable from '../components/billing/InvoiceTable';
import PaymentModal from '../components/payment/PaymentModal';
import { formatCurrency, formatDate, getStatusBadgeColor } from '../utils/formatters';
import {
  FileText,
  CreditCard,
  Eye,
  Filter,
  RefreshCw,
  Search,
  CheckCircle,
} from 'lucide-react';

const Invoices = () => {
  const { role, user } = useAuth();
  const [invoices, setInvoices] = useState([]);
  const [pagination, setPagination] = useState({ page: 1, limit: 10, total: 0, totalPages: 1 });
  const [loading, setLoading] = useState(true);
  const [status, setStatus] = useState('');
  const [billingPeriod, setBillingPeriod] = useState('');

  // Modals
  const [selectedInvoiceDetail, setSelectedInvoiceDetail] = useState(null);
  const [selectedInvoiceForPay, setSelectedInvoiceForPay] = useState(null);

  const fetchInvoices = async (page = 1) => {
    try {
      setLoading(true);
      const res = await invoiceApi.getInvoices({
        status: status || undefined,
        billingPeriod: billingPeriod || undefined,
        page,
        limit: 10,
      });

      if (res.success) {
        setInvoices(res.data);
        setPagination(res.pagination);
      }
    } catch (err) {
      console.error(err);
    } finally {
      setLoading(false);
    }
  };

  useEffect(() => {
    fetchInvoices(1);
  }, [status, billingPeriod, role]);

  const handlePaymentSuccess = () => {
    fetchInvoices(pagination.page);
  };

  const columns = [
    {
      header: 'Invoice #',
      accessor: 'invoiceNumber',
      className: 'font-mono font-bold text-blue-600',
    },
    {
      header: 'Subscriber',
      render: (row) => (
        <div>
          <span className="font-semibold text-slate-800 block">
            {row.customerId?.customerCode || 'CUST'}
          </span>
          <span className="text-[11px] text-slate-400">
            {row.customerId?.userId?.name || user?.name}
          </span>
        </div>
      ),
    },
    {
      header: 'Cycle',
      accessor: 'billingPeriod',
      className: 'font-mono text-xs text-slate-600',
    },
    {
      header: 'Base Rate',
      render: (row) => <span>{formatCurrency(row.baseAmount)}</span>,
    },
    {
      header: 'Overage',
      render: (row) => (
        <span className={row.usageAmount > 0 ? 'text-amber-700 font-semibold' : 'text-slate-400'}>
          {formatCurrency(row.usageAmount)}
        </span>
      ),
    },
    {
      header: 'Taxes (18%)',
      render: (row) => <span className="text-slate-600">{formatCurrency(row.tax)}</span>,
    },
    {
      header: 'Total Payable',
      render: (row) => (
        <span className="font-extrabold text-slate-900 text-sm">
          {formatCurrency(row.totalAmount)}
        </span>
      ),
    },
    {
      header: 'Due Date',
      render: (row) => <span className="text-slate-600 text-xs">{formatDate(row.dueDate)}</span>,
    },
    {
      header: 'Status',
      render: (row) => (
        <span
          className={`px-2.5 py-1 rounded-full text-[10px] font-bold border uppercase tracking-wider ${getStatusBadgeColor(
            row.status
          )}`}
        >
          {row.status}
        </span>
      ),
    },
    {
      header: 'Actions',
      align: 'right',
      render: (row) => (
        <div className="flex items-center justify-end gap-1.5">
          <Button
            variant="outline"
            size="sm"
            icon={Eye}
            onClick={() => setSelectedInvoiceDetail(row)}
          >
            Details
          </Button>
          {row.status === 'PENDING' && (
            <Button
              variant="primary"
              size="sm"
              icon={CreditCard}
              onClick={() => setSelectedInvoiceForPay(row)}
            >
              Pay
            </Button>
          )}
        </div>
      ),
    },
  ];

  return (
    <div className="space-y-6">
      {/* Header */}
      <div className="flex flex-wrap items-center justify-between gap-4 bg-white p-6 rounded-2xl border border-slate-200/80 shadow-xs">
        <div>
          <span className="text-xs uppercase font-extrabold tracking-wider text-blue-600">
            Billing Statements
          </span>
          <h1 className="text-2xl font-bold text-slate-800 tracking-tight mt-0.5">
            Telecom Tax Invoices
          </h1>
          <p className="text-xs text-slate-500 mt-1">
            Official monthly invoices generated by backend calculation engine with due dates and payment statuses.
          </p>
        </div>

        <div className="flex items-center gap-2">
          <Button variant="outline" size="sm" icon={RefreshCw} onClick={() => fetchInvoices(1)}>
            Refresh
          </Button>
        </div>
      </div>

      {/* Filter Bar (Page 11 InvoiceFilter) */}
      <InvoiceFilter
        status={status}
        setStatus={setStatus}
        billingPeriod={billingPeriod}
        setBillingPeriod={setBillingPeriod}
      />

      {/* Invoices Table (Page 11 InvoiceTable with InvoiceRow) */}
      <InvoiceTable
        invoices={invoices}
        loading={loading}
        pagination={pagination}
        onPageChange={(p) => fetchInvoices(p)}
        onSelectDetail={(inv) => setSelectedInvoiceDetail(inv)}
        onPayNow={(inv) => setSelectedInvoiceForPay(inv)}
        userName={user?.name}
      />

      {/* Invoice Details Modal */}
      <Modal
        isOpen={!!selectedInvoiceDetail}
        onClose={() => setSelectedInvoiceDetail(null)}
        title="Telecom Tax Invoice"
        subtitle="Itemized billing statement"
        maxWidth="max-w-2xl"
      >
        <InvoiceDetails
          invoice={selectedInvoiceDetail}
          onPayNow={(inv) => {
            setSelectedInvoiceDetail(null);
            setSelectedInvoiceForPay(inv);
          }}
          onClose={() => setSelectedInvoiceDetail(null)}
        />
      </Modal>

      {/* Payment Modal */}
      <PaymentModal
        isOpen={!!selectedInvoiceForPay}
        onClose={() => setSelectedInvoiceForPay(null)}
        invoice={selectedInvoiceForPay}
        onPaymentSuccess={handlePaymentSuccess}
      />
    </div>
  );
};

export default Invoices;
